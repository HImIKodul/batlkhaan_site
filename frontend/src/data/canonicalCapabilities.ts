export function capabilityDefinition(area:BusinessAreaId,id?:string|null,name?:string|null):string{
  const row=resolveCanonicalCapability(area,id,name);
  const label=row?.name||name?.trim()||id?.trim()||'Энэ чадавх';
  if(row?.definition?.trim())return row.definition.trim();
  if(area==='marketing')return marketingDefinition(label);
  const areaName=area==='it'?'мэдээллийн технологи':area==='finance'?'санхүү':area==='people'?'хүний нөөц':'үйлдвэрлэл ба үйл ажиллагаа';
  return `“${label}” нь ${areaName} чиглэлд тухайн асуудлыг бодлого, процесс, хариуцлага, мэдээлэл ба хэмжилтийн уялдаагаар тогтвортой удирдах байгууллагын чадавх юм.`;
}

