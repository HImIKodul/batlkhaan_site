function normalize(value:string){
  return value
    .toLocaleLowerCase('mn-MN')
    .replace(/[·:–-]+/g,' ')
    .replace(/\s+/g,' ')
    .trim();
}

export function resolveCanonicalCapability(area:BusinessAreaId,id?:string|null,name?:string|null):CanonicalCapability|undefined{
  const rows=canonicalCapabilities[area]||[];
  const cleanId=(id||'').trim().toUpperCase();
  if(cleanId){
    const byId=rows.find(row=>row.id.toUpperCase()===cleanId||row.runtimeIds.some(x=>x.toUpperCase()===cleanId));
    if(byId)return byId;
  }
  if(name){
    const target=normalize(name);
    const byName=rows.find(row=>normalize(row.name)===target);
    if(byName)return byName;
  }
  return undefined;
}

export function canonicalCapabilityName(area:BusinessAreaId,id?:string|null,name?:string|null):string{
  return resolveCanonicalCapability(area,id,name)?.name||name?.trim()||id?.trim()||'-';
}

