import fs from 'node:fs';
let pass=0, fail=0;
const ck=(name,ok,detail='')=>{console.log(`${ok?'PASS':'FAIL'} ${name}${detail?` — ${detail}`:''}`);ok?pass++:fail++};
const overlay=fs.readFileSync(new URL('../src/question-bank-overlay.ts',import.meta.url),'utf8');
const prepare=fs.readFileSync(new URL('../src/prepare-question-bank-overlay.ts',import.meta.url),'utf8');
const exportSrc=fs.readFileSync(new URL('../src/export-question-bank-overlay-template.ts',import.meta.url),'utf8');
const pkg=JSON.parse(fs.readFileSync(new URL('../package.json',import.meta.url),'utf8'));
ck('overlay format version pinned',overlay.includes('MMRI-QBANK-OVERLAY-1'));
ck('base bundle SHA binding required',overlay.includes('BASE_SHA')&&overlay.includes('baseBundleSha256'));
ck('new immutable methodology version required',overlay.includes('IMMUTABLE_VERSION'));
ck('exact category count enforced',overlay.includes('CATEGORY_COUNT'));
ck('unknown category IDs rejected',overlay.includes('CATEGORY_UNKNOWN'));
ck('exact question count enforced',overlay.includes('QUESTION_COUNT'));
ck('duplicate question IDs rejected',overlay.includes('QUESTION_DUPLICATE'));
ck('unknown question IDs rejected',overlay.includes('QUESTION_UNKNOWN'));
ck('exact option count enforced',overlay.includes('OPTION_COUNT'));
ck('option index/order enforced',overlay.includes('OPTION_INDEX'));
ck('empty question wording rejected',overlay.includes('QUESTION_TEXT_EMPTY'));
ck('em dash rejected in questions',overlay.includes('QUESTION_EM_DASH'));
ck('em dash rejected in options',overlay.includes('OPTION_EM_DASH'));
ck('placeholder wording rejected',overlay.includes('QUESTION_PLACEHOLDER')&&overlay.includes('OPTION_PLACEHOLDER'));
ck('strict Mongolian mode supported',overlay.includes('strictMongolian')&&prepare.includes('MMRI_QBANK_MONGOLIAN_ONLY'));
ck('structural fingerprint protects scoring/routing',overlay.includes('structuralFingerprint')&&prepare.includes('STRUCTURAL_DRIFT'));
ck('explicit option score/state preserved',overlay.includes('...o')&&overlay.includes('labelMn: optionsMn[i]'));
ck('candidate bundle revalidated',prepare.includes('validateBundle(candidate)'));
ck('candidate manifest emitted',prepare.includes('.manifest.json'));
ck('review template exporter exists',exportSrc.includes('createQuestionBankOverlayTemplate'));
ck('package export command exists',Boolean(pkg.scripts['qbank:overlay:export']));
ck('package prepare command exists',Boolean(pkg.scripts['qbank:overlay:prepare']));
ck('step14 verification command exists',Boolean(pkg.scripts['backend:step14:qbank:verify']));
console.log(`\nSTEP14 QBANK STATIC: ${pass}/${pass+fail} PASS`);
if(fail) process.exit(1);
