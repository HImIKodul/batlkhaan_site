import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const diagTypes=read('src/diagnosis/types.ts');
const diag=read('src/diagnosis/result.ts');
const reportTypes=read('src/report/types.ts');
const report=read('src/report/payload.ts');
const validator=read('src/report/validator.ts');
const fallback=read('src/report/fallback-renderer.ts');
const prompt=read('src/report/ai-prompt.ts');
const query=read('src/api/services/query-service.ts');
const results=read('../frontend/src/pages/Results.tsx');
const reportPage=read('../frontend/src/pages/Report.tsx');
const frontTypes=read('../frontend/src/api/types.ts');
const backPkg=JSON.parse(read('package.json'));
const frontPkg=JSON.parse(read('../frontend/package.json'));
const checks=[]; const check=(name,pass,detail='')=>checks.push({name,pass:Boolean(pass),detail:String(detail??'')});
check('backend version 3.25.0',backPkg.version==='3.25.0',backPkg.version);
check('frontend version 3.25.0',frontPkg.version==='3.25.0',frontPkg.version);
check('diagnosis has review-required metric',diagTypes.includes('REVIEW_REQUIRED_SCORE'));
check('diagnosis has review-required result status',diagTypes.includes('"REVIEW_REQUIRED"'));
check('completed-with-review not in official set',diag.includes('const TERMINAL_OFFICIAL = new Set(["COMPLETED"])'));
check('review metric branch exists',diag.includes('status === "COMPLETED_WITH_REVIEW"')&&diag.includes('"REVIEW_REQUIRED_SCORE"'));
check('review score is non-official',diag.includes('isOfficial:overallMetric.metricType==="OFFICIAL_OVERALL_SCORE"'));
check('weak cells split validated/provisional',diagTypes.includes('validatedWeakCellCount')&&diagTypes.includes('provisionalWeakCellCount')&&diagTypes.includes('provisionalWeakCells'));
check('validated weakness requires direct final',diag.includes('c.status==="DIRECT_FINAL"'));
check('validated weakness requires locked confidence state',diag.includes('c.confidenceState==="LOCKED"'));
check('validated weakness requires >=0.8 confidence',diag.includes('c.effectiveConfidence>=0.8'));
check('contradicted cell cannot be validated weakness',diag.includes('!c.hasHardContradiction'));
check('strength excludes review-required categories',diag.includes('c.reviewRequiredCellCount===0'));
check('strength excludes unresolved categories',diag.includes('c.unresolvedCellCount===0'));
check('quality has review flag',diagTypes.includes('requiresReview: boolean'));
check('quality has official-result flag',diagTypes.includes('officialResultAvailable: boolean'));
check('quality has quick-estimate flag',diagTypes.includes('quickEstimate: boolean'));
check('review warning prevents final interpretation',diag.includes('баталгаажсан эцсийн үр дүн гэж ангилахгүй'));
check('quick coverage-confidence warning exists',diag.includes('100% value coverage'));
check('quick warning no universal 280 claim',!diag.includes('280 асуултын хязгаарт'));
check('root causes marked hypothesis not causal',diagTypes.includes('DIAGNOSTIC_HYPOTHESIS_NOT_CAUSAL')&&diag.includes('isProvisional:overallMetric.resultStatus!=="OFFICIAL"'));
check('five outcomes preserved',diag.includes('["P1","P2","P3","P4","P5"]'));
check('ROI guardrail preserved',diag.includes('roiPredictionAllowed:false'));
check('causal lift guardrail preserved',diag.includes('causalFinancialLiftClaimAllowed:false'));
check('report supports review-required metric',reportTypes.includes('REVIEW_REQUIRED_SCORE'));
check('report only clean completed is official',report.includes('officialScore !== null && status === "COMPLETED"'));
check('report review branch exists',report.includes('status === "COMPLETED_WITH_REVIEW"')&&report.includes('REVIEW_REQUIRED_SCORE'));
check('report review keeps numeric score',report.includes('metric === "OFFICIAL_OVERALL_SCORE" || metric === "REVIEW_REQUIRED_SCORE"'));
check('report strength excludes review categories',report.includes('(r?.reviewRequiredCellCount ?? 0) === 0'));
check('report strength excludes unresolved categories',report.includes('(r?.unresolvedCellCount ?? 0) === 0'));
check('report warning review required',report.includes('REVIEW_REQUIRED төлөвтэй'));
check('report quick limit no universal 280 claim',!report.includes('QUICK үнэлгээ 280 асуултын хязгаарт'));
check('validator blocks official wording for review',validator.includes('Review-required score is described as official/final'));
check('validator requires review terminology',validator.includes('Review-required terminology is missing'));
check('fallback labels review score',fallback.includes('Нягтлах шаардлагатай урьдчилсан оноо'));
check('AI prompt forbids official review claims',prompt.includes('QUICK and REVIEW_REQUIRED results must never be described as official/final'));
check('assessment list official flag status-aware',query.includes('isOfficial:a.status==="COMPLETED"&&a.overallOfficialScore!==null'));
check('assessment progress official flag status-aware',query.includes('officialResultAvailable:a.status==="COMPLETED"&&a.overallOfficialScore!==null'));
check('frontend types include provisional weaknesses',frontTypes.includes('provisionalWeakCellCount')&&frontTypes.includes('provisionalWeakCells'));
check('frontend types include quality official flag',frontTypes.includes('officialResultAvailable:boolean'));
check('frontend results labels review-required',results.includes('Нягтлах шаардлагатай урьдчилсан үнэлгээ'));
check('frontend results labels QUICK provisional',results.includes('QUICK урьдчилсан үнэлгээ'));
check('frontend results separates validated/provisional weak cells',results.includes('Баталгаажсан сул нүдүүд')&&results.includes('Урьдчилсан анхаарах дохио'));
check('frontend executive summary does not force provisional weak as validated',results.includes("weakestCell?'Нотолгоогоор баталгаажсан сул нүд':'Урьдчилсан анхаарах дохио'"));
check('frontend root causes have provisional wording',results.includes('Урьдчилсан шалтгааны таамаглал'));
check('frontend outcomes mark provisional direction',results.includes('Урьдчилсан бизнесийн чиглэл'));
check('frontend status explicit review required',results.includes("data.resultStatus==='REVIEW_REQUIRED'"));
check('frontend report labels review-required',reportPage.includes("p.metricType==='REVIEW_REQUIRED_SCORE'"));
check('demo QUICK progress not official',results.includes('officialResultAvailable:false'));
check('results still show confidence separate from score',results.includes('Онооноос тусдаа confidence ба coverage'));
check('results still show ROI guardrail',results.includes('ROI загвар биш'));
check('results still show causal guardrail',results.includes('батлагдсан causal claim биш'));
check('result hash provenance still visible',results.includes('result.resultHash.slice(0,12)'));
check('no evidence upload introduced',!results.toLowerCase().includes('upload'));
const failed=checks.filter(x=>!x.pass);
const out={schema:'mmri.step07_of15.results_diagnosis.static.v1',status:failed.length?'FAIL':'PASS',checksPassed:checks.length-failed.length,checksTotal:checks.length,failures:failed,checks};
fs.writeFileSync('STEP07_RESULTS_DIAGNOSIS_STATIC_VALIDATION.json',JSON.stringify(out,null,2)+'\n');
console.log(JSON.stringify({status:out.status,passed:out.checksPassed,total:out.checksTotal,failures:out.failures},null,2));
if(failed.length)process.exit(1);
