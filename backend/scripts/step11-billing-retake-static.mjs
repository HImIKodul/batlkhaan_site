import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.cwd(),'..');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const billing=read('backend/src/billing/billing-service.ts');
const app=read('backend/src/api/app.ts');
const config=read('backend/src/api/config.ts');
const qpay=read('backend/src/billing/qpay-client.ts');
const hub=read('frontend/src/pages/DiagnosisHub.tsx');
const billPage=read('frontend/src/pages/Billing.tsx');
const landing=read('frontend/src/pages/Landing.tsx');
const start=read('START_LOCAL.sh');
const benv=read('backend/.env.example');
const fenv=read('frontend/.env.example');
const checks=[]; const check=(name,pass,detail='')=>checks.push({name,pass:Boolean(pass),detail});
check('diagnostic_plan_exists',billing.includes('DIAGNOSTIC:{name:"Анхны оношилгоо"'));
check('retake_plan_exists',billing.includes('RETAKE:{name:"Дахин оношилгоо"'));
check('retake_requires_prior_completed',billing.includes('RETAKE_NOT_AVAILABLE')&&billing.includes('COMPLETED_WITH_REVIEW')&&billing.includes('EXHAUSTED'));
check('same_entitlement_claim_path',billing.includes('const expectedPlan:BillingPlanCode=prior?"RETAKE":"DIAGNOSTIC"')&&billing.includes('planCode:expectedPlan')&&billing.includes('sourceInvoice:{status:"PAID"}'));
check('entitlement_consumed_once',billing.includes('assessmentsUsed:{lt:1}')&&billing.includes('assessmentsUsed:{increment:1},status:"CONSUMED"'));
check('payment_required_when_enforced',billing.includes('ApiError(402,"PAYMENT_REQUIRED"'));
check('assessment_creation_claims_entitlement',app.includes('billing.claimAssessmentEntitlement(params.companyId,domainCode)'));
check('qpay_get_callback_route',app.includes('router.add("GET","/api/v1/billing/qpay/callback/:invoiceId"'));
check('qpay_post_callback_route',app.includes('router.add("POST","/api/v1/billing/qpay/callback/:invoiceId"'));
check('mock_pay_route_present',app.includes('/api/v1/billing/invoices/:invoiceId/mock-pay'));
check('mock_pay_disabled_in_production',billing.includes('this.config.environment==="production"||this.provider.name!=="MOCK"'));
check('qpay_verifies_payment',qpay.includes('/v2/payment/check')&&billing.includes('checkInvoicePayment'));
check('partial_payment_rejected',billing.includes('PARTIAL_PAYMENT')&&billing.includes('paidAmount<current.amountMnt'));
check('callback_token_hashed',billing.includes('callbackTokenHash:hashToken(callbackToken)')&&billing.includes('timingSafeEqual'));
check('provider_metadata_allowlist',billing.includes('const allow=["count","paid_amount","invoice_id","payment_id","payment_status","payment_amount","mode","confirmed"]'));
check('retake_default_300k_backend',config.includes('priceEnv("MMRI_RETAKE_PRICE_MNT")??300000'));
check('diagnostic_300k_backend_env',benv.includes('MMRI_DIAGNOSTIC_PRICE_MNT="300000"')&&start.includes('MMRI_DIAGNOSTIC_PRICE_MNT="300000"'));
check('retake_300k_start',start.includes('MMRI_RETAKE_PRICE_MNT="300000"'));
check('frontend_diagnostic_300k',fenv.includes('VITE_MMRI_DIAGNOSTIC_PRICE_MNT=300000')&&billPage.includes('plan?.amountMnt??300000'));
check('hub_checks_retake_entitlement',hub.includes("paidFor(id,'RETAKE')"));
check('hub_checks_first_entitlement',hub.includes("paidFor(id,'DIAGNOSTIC')"));
check('billing_page_selects_retake',billPage.includes("mode==='retake'?'RETAKE':'DIAGNOSTIC'"));
check('landing_states_retake_300k',landing.includes('Дахин оношлуулах төлбөр 300,000₮'));
check('no_subscription_plan',!billing.includes('MONTHLY')&&!billing.includes('ANNUAL')&&!billing.includes('SUBSCRIPTION'));
const failed=checks.filter(x=>!x.pass);
const report={schema:'mmri.step11.billing_retake.static.v1',status:failed.length?'FAIL':'PASS',checksPassed:checks.length-failed.length,checksTotal:checks.length,failed,checks};
fs.writeFileSync(path.resolve(root,'STEP11_BILLING_RETAKE_STATIC.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({status:report.status,checksPassed:report.checksPassed,checksTotal:report.checksTotal,failed},null,2));
if(failed.length) process.exit(1);
