import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const cfg=read('src/api/config.ts');
const app=read('src/api/app.ts');
const crypto=read('src/api/auth/crypto.ts');
const auth=read('src/api/auth/auth-service.ts');
const cookies=read('src/api/auth/cookies.ts');
const limiter=read('src/api/http/rate-limit.ts');
const server=read('src/api/server.ts');
const rolePolicy=read('src/api/auth/role-policy.ts');
const pkg=JSON.parse(read('package.json'));
const releaseGate=fs.readFileSync(path.join(root,'../VERIFY_STEP11_FULL_REGRESSION.sh'),'utf8');
const checks=[]; const check=(name,ok)=>checks.push({name,status:ok?'PASS':'FAIL'});
check('production_secure_cookie_fail_closed',cfg.includes('COOKIE_SECURE must be true in production'));
check('production_https_origin_enforced',cfg.includes('Production origin must use HTTPS'));
check('origin_normalization',cfg.includes('.map(normalizeOrigin)')&&cfg.includes('return url.origin'));
check('secrets_must_be_distinct',cfg.includes('must be distinct'));
check('access_token_ttl_bounded',cfg.includes('must not exceed 1800'));
check('refresh_token_ttl_bounded',cfg.includes('must not exceed 90 days'));
check('qpay_https_production_guard',cfg.includes('QPAY_BASE_URL')&&cfg.includes('must use HTTPS in production'));
check('callback_not_local_in_production',cfg.includes('MMRI_BILLING_CALLBACK_BASE_URL')&&cfg.includes('must not use a local hostname'));
check('request_body_limit_configured',cfg.includes('REQUEST_BODY_LIMIT_BYTES')&&app.includes('config.requestBodyLimitBytes'));
check('server_timeout_controls',server.includes('requestTimeout=config.requestTimeoutMs')&&server.includes('headersTimeout=config.headersTimeoutMs')&&server.includes('keepAliveTimeout=config.keepAliveTimeoutMs'));
check('bounded_general_api_rate_limit',app.includes('apiLimiter.check')&&cfg.includes('API_RATE_LIMIT'));
check('auth_ip_rate_limit',app.includes('authIpLimiter.check')&&cfg.includes('AUTH_IP_RATE_LIMIT'));
check('auth_account_rate_limit',app.includes('authAccountLimiter.check')&&app.includes('hashAuditValue'));
check('refresh_rate_limit',app.includes('refreshLimiter.check')&&cfg.includes('REFRESH_RATE_LIMIT'));
check('limiter_memory_bounded',limiter.includes('maxBuckets=50_000')&&limiter.includes('this.prune'));
check('retry_after_exposed',app.includes('retry-after')&&limiter.includes('retryAfterSeconds'));
check('refresh_logout_origin_guard',app.includes('requireTrustedBrowserOrigin(req,config)'));
check('request_id_bounded',app.includes('safeRequestId')&&app.includes('{1,128}'));
check('security_headers_extended',app.includes('permissions-policy')&&app.includes('cross-origin-opener-policy')&&app.includes('strict-transport-security'));
check('jwt_header_algorithm_validated',crypto.includes('parsedHeader.alg!=="HS256"')&&crypto.includes('parsedHeader.typ!=="JWT"'));
check('jwt_claim_shape_and_lifetime_validated',crypto.includes('claims.iat > now + 60')&&crypto.includes('claims.exp - claims.iat > config.accessTokenTtlSeconds + 5'));
check('login_timing_dummy_hash',auth.includes('dummyPasswordHash')&&auth.includes('user?.passwordHash??await this.dummyPasswordHash'));
check('refresh_replay_family_revocation_preserved',auth.includes('REFRESH_REPLAY')&&auth.includes('tokenVersion: { increment: 1 }'));
check('malformed_cookie_does_not_500',cookies.includes('catch{continue;}'));
check('last_owner_cannot_be_removed',app.includes('assertOwnerTransitionAllowed')&&rolePolicy.includes('A company must retain at least one OWNER')&&rolePolicy.includes('ownerCount<=1'));
check('graceful_shutdown_disconnects_prisma',server.includes('prisma.$disconnect()')&&server.includes('hardStop'));
const apiVersion=app.match(/version:"([^"]+)"/)?.[1]??null;
check('api_health_version_consistent',Boolean(apiVersion)&&server.includes(`MMRI API v${apiVersion}`)&&server.includes(`version:"${apiVersion}"`),String(apiVersion));
const [maj,min,patch]=String(pkg.version??'0.0.0').split('.').map(Number);
check('backend_release_version_nonregressed',maj>3||(maj===3&&(min>24||(min===24&&patch>=0))),pkg.version);
check('security_verify_in_release_chain',String(pkg.scripts?.['release:verify']||'').includes('security:verify')||(String(pkg.scripts?.['release:verify']||'').includes('VERIFY_STEP11_FULL_REGRESSION.sh')&&releaseGate.includes('step13-security-static-acceptance.mjs')&&releaseGate.includes('step13-security-runtime.mjs')));
const passed=checks.filter(x=>x.status==='PASS').length;
const result=passed===checks.length?'PASS':'FAIL';
console.log(JSON.stringify({step:21,release:'v3.9.0',scope:'production security + tenant/RBAC/session hardening',passed,total:checks.length,result,checks},null,2));
if(result!=='PASS')process.exit(1);
