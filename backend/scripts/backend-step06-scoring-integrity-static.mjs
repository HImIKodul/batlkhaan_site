import fs from 'node:fs';
const checks=[];
const check=(name,pass,detail='')=>checks.push({name,pass:Boolean(pass),detail:String(detail)});
const calculation=fs.readFileSync('src/engine/calculation.ts','utf8');
const evidence=fs.readFileSync('src/engine/evidence.ts','utf8');
const integrity=fs.readFileSync('src/engine/integrity.ts','utf8');
check('runtime scoring boundary validates evidence',calculation.includes('assertEvidenceIntegrity(definition, evidence)'));
check('runtime scoring boundary validates output snapshot',calculation.includes('assertRuntimeSnapshotIntegrity(definition, snapshot)'));
check('explicit authority is clamped',evidence.includes('const authority = clamp('));
check('duplicate effective question evidence is rejected',integrity.includes('Duplicate effective evidence for question'));
check('question/category/cell/path metadata is canonicalized by validation',integrity.includes('Evidence category mismatch')&&integrity.includes('Evidence cell mismatch')&&integrity.includes('Evidence path mismatch'));
check('option score/state are validated against frozen question',integrity.includes('Evidence state mismatch')&&integrity.includes('Evidence score mismatch'));
check('reliability is recomputed from canonical authority/path',integrity.includes('reliabilityForPath')&&integrity.includes('Evidence reliability is not canonical'));
check('cell/category/module/overall ranges are guarded',integrity.includes('Runtime cell count mismatch')&&integrity.includes('Overall official score'));
check('category to module contribution lineage guarded',integrity.includes('Category official contributions for module'));
check('module to overall contribution lineage guarded',integrity.includes('Module official contributions to overall'));
const failures=checks.filter(x=>!x.pass);
console.log(JSON.stringify({status:failures.length?'FAIL':'PASS',checksPassed:checks.length-failures.length,checksTotal:checks.length,failures,checks},null,2));
if(failures.length)process.exit(1);
