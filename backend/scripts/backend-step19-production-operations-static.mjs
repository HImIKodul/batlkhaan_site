import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const checks=[];const ck=(name,ok)=>{checks.push({name,ok});if(!ok)console.error('FAIL',name)};
const server=read('src/api/server.ts'), app=read('src/api/app.ts'), obs=read('src/api/observability.ts'), cfg=read('src/api/config.ts');
const compose=read('../deploy/docker-compose.production.yml'), env=read('../deploy/.env.production.example');
const release=read('../ops/release-gate.sh'), connected=read('../ops/connected-release-gate.sh'), deploy=read('../ops/deploy-production.sh'), rollback=read('../ops/rollback-application.sh'), preflight=read('../ops/preflight.mjs');
ck('drain-before-shutdown',server.includes('beginDrain();')&&server.includes('service_draining'));
ck('bounded-shutdown',server.includes('shutdownForceTimeoutMs')&&server.includes('closeAllConnections'));
ck('idle-connections-closed',server.includes('closeIdleConnections'));
ck('prisma-disconnect',server.includes('prisma.$disconnect'));
ck('customer-traffic-rejected-while-draining',app.includes('SERVICE_DRAINING'));
ck('ready-checks-db-and-storage',app.includes('databaseReady')&&app.includes('reportStorageReady'));
ck('liveness-db-independent',app.includes('GET","/live')&&!app.slice(app.indexOf('GET","/live'),app.indexOf('GET","/health')).includes('prisma'));
ck('metrics-authenticated',app.includes('validMetricsCredential'));
ck('metrics-traffic-gauge',obs.includes('mmri_accepting_traffic'));
ck('metrics-memory',obs.includes('mmri_process_resident_memory_bytes')&&obs.includes('mmri_process_heap_used_bytes'));
ck('request-logs-bounded',obs.includes('requestId')&&obs.includes('durationMs')&&obs.includes('releaseSha')&&obs.includes('instanceId'));
ck('internal-errors-request-correlated',app.includes('internal_exception')&&app.includes('requestId:context?.requestId'));
ck('shutdown-env-configured',cfg.includes('SHUTDOWN_DRAIN_MS')&&cfg.includes('SHUTDOWN_FORCE_TIMEOUT_MS'));
ck('shutdown-order-validated',cfg.includes('must be greater than SHUTDOWN_DRAIN_MS'));
ck('preflight-validates-shutdown-timing',preflight.includes('SHUTDOWN_FORCE_TIMEOUT_MS must be 30000..120000'));
ck('production-force-timeout-minimum',cfg.includes('must be at least 30000 in production'));
ck('compose-stop-grace',compose.includes('stop_grace_period: 50s')&&compose.includes('stop_signal: SIGTERM'));
ck('compose-api-init',/api:[\s\S]*?init: true/.test(compose));
ck('compose-log-rotation',compose.includes('max-size: "20m"')&&compose.includes('max-file: "5"'));
ck('compose-ready-healthcheck',compose.includes("fetch('http://127.0.0.1:4000/ready')"));
ck('env-documents-shutdown',env.includes('SHUTDOWN_DRAIN_MS=5000')&&env.includes('SHUTDOWN_FORCE_TIMEOUT_MS=45000'));
ck('release-gate-current-not-stale',release.includes('backend-step19-production-operations-static.mjs')&&!release.includes('step14-production-ops-static.mjs'));
ck('release-gate-connected-explicit',release.includes('MMRI_CONNECTED_RELEASE_GATE'));
ck('connected-gate-db',connected.includes('connected-production-db-gate.sh'));
ck('connected-gate-backup',connected.includes('backup-all.sh')&&connected.includes('verify-backup-set.sh'));
ck('connected-gate-stability',connected.includes('stability-check.mjs'));
ck('deploy-explicit-confirmation',deploy.includes('MMRI_DEPLOY_PRODUCTION=YES'));
ck('deploy-order-backup-before-migrate',deploy.indexOf('backup-all.sh')<deploy.indexOf('run --rm migrate'));
ck('deploy-api-before-web',deploy.indexOf('up -d --no-deps api')<deploy.indexOf('up -d web'));
ck('rollback-explicit-confirmation',rollback.includes('MMRI_ROLLBACK_APPLICATION=YES'));
ck('rollback-schema-compatibility-guard',rollback.includes('MMRI_ROLLBACK_SCHEMA_COMPATIBLE=YES'));
ck('rollback-never-reverses-migrations',rollback.includes('Database migrations were NOT reversed'));
ck('release-manifest-script',fs.existsSync('../ops/create-release-manifest.mjs'));
ck('stability-check-script',fs.existsSync('../ops/stability-check.mjs'));
ck('runbook-present',fs.existsSync('../deploy/RELEASE_RUNBOOK.md'));
ck('observability-doc-present',fs.existsSync('../deploy/OBSERVABILITY.md'));
const failed=checks.filter(x=>!x.ok);console.log(JSON.stringify({status:failed.length?'FAIL':'PASS',checks:checks.length,passed:checks.length-failed.length,failed},null,2));if(failed.length)process.exit(1);
