#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
CSS="$ROOT/frontend/src/release-r1721-4-step15.css"
TSX="$ROOT/frontend/src/components/BusinessRadar.tsx"
MAIN="$ROOT/frontend/src/main.tsx"
fail(){ echo "FAIL: $1" >&2; exit 1; }
pass(){ echo "PASS: $1"; }
[[ -f "$CSS" ]] || fail "Step 15 CSS missing"
[[ -f "$TSX" ]] || fail "BusinessRadar.tsx missing"
grep -q "iconR=188" "$TSX" || fail "fixed icon orbit radius missing"
grep -q "release-r1721-4-step15.css" "$MAIN" || fail "Step 15 CSS not imported last"
grep -q "left:calc(var(--radar-x) - (var(--step15-icon-size) / 2))!important" "$CSS" || fail "explicit left geometry missing"
grep -q "top:calc(var(--radar-y) - (var(--step15-icon-size) / 2))!important" "$CSS" || fail "explicit top geometry missing"
grep -q "transform:none!important" "$CSS" || fail "stationary transform override missing"
grep -q "translate:none!important" "$CSS" || fail "stationary translate override missing"
grep -q "scale:none!important" "$CSS" || fail "stationary scale override missing"
grep -q "animation:none!important" "$CSS" || fail "animation disable missing"
grep -q "overflow:visible!important" "$CSS" || fail "icon clipping protection missing"
grep -q "business-radar__center:not(.has-score)" "$CSS" || fail "logged-out center rule missing"
grep -A18 "business-radar__center:not(.has-score)" "$CSS" | grep -q "background:transparent!important" || fail "logged-out white background still present"
grep -q "business-radar__average-tooltip::after{display:none!important;content:none!important}" "$CSS" || fail "average tooltip pointer not removed"
grep -A8 "business-radar__average-tooltip span" "$CSS" | grep -q "font-size:17px!important" || fail "average score label not enlarged"
pass "fixed five-icon geometry"
pass "no transform/translate/scale motion"
pass "SVG clipping protection"
pass "logged-out transparent center"
pass "clean enlarged average-score label"
echo "STEP 15 HOME RADAR GEOMETRY: PASS"
